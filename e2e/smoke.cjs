const { chromium } = require('playwright');
const fs = require('node:fs');
fs.mkdirSync('artifacts/screenshots', { recursive: true });
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto(process.env.SMOKE_URL||'http://127.0.0.1:4173',{waitUntil:'networkidle'});
 await page.waitForSelector('#stats .stat');
 if(await page.locator('#stats .stat').count()!==4)throw Error('Dashboard metrics missing');
 if(await page.locator('#endpointCards .panel').count()===0)throw Error('Demo endpoints missing');
 await page.screenshot({path:'artifacts/screenshots/01-dashboard.png',fullPage:true});
 await page.click('[data-view="replay"]');
 await page.selectOption('#replayProfile','rate-limit');
 await page.click('#runReplay');
 await page.waitForSelector('#replayTimeline .eventrow');
 const timeline=await page.locator('#replayTimeline').innerText();
 if(!timeline.includes('429')||!timeline.includes('Delivered successfully'))throw Error('Rate-limit retry scenario did not recover');
 await page.screenshot({path:'artifacts/screenshots/02-replay-lab.png',fullPage:true});
 await page.click('[data-view="signatures"]');
 await page.click('#generateSignature');
 await page.waitForSelector('#signatureOutput:not(.hidden)');
 await page.click('#verifyHmac');
 if(!(await page.locator('#verifyResult').innerText()).includes('VALID SIGNATURE'))throw Error('Valid HMAC did not verify');
 await page.click('#tamperBody');
 await page.click('#verifyHmac');
 if(!(await page.locator('#verifyResult').innerText()).includes('SIGNATURE MISMATCH'))throw Error('Tampered payload was not rejected');
 await page.click('[data-view="idempotency"]');
 await page.click('#runIdempotency');
 await page.waitForSelector('#idemTimeline .eventrow');
 if(!(await page.locator('#idemResult').innerText()).includes('2'))throw Error('Idempotency simulator did not suppress duplicate deliveries');
 const idemState=await page.evaluate(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')));
 if(!idemState||!Array.isArray(idemState.idempotencyRuns)||!idemState.idempotencyRuns.length)throw Error('Idempotency history did not persist');
 await page.click('[data-view="contracts"]');
 await page.click('#compareContracts');
 await page.waitForSelector('#contractDiff table');
 if(!(await page.locator('#contractVerdict').innerText()).includes('BREAKING'))throw Error('Contract diff did not flag breaking changes');
 const contractState=await page.evaluate(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')));
 if(!contractState||!Array.isArray(contractState.contractRuns)||!contractState.contractRuns.length)throw Error('Contract comparison did not persist');
 const contractDlPromise=page.waitForEvent('download');
 await page.click('#exportContractReport');
 const contractDl=await contractDlPromise;
 if(!contractDl.suggestedFilename().endsWith('.md'))throw Error('Contract report export failed');
 await page.locator('[data-view="settings"]').first().click();
 await page.locator('#view-settings').waitFor({state:'visible'});
 const before=await page.locator('#dbDetails').innerText();
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-view="settings"]').first().click();
 await page.locator('#view-settings').waitFor({state:'visible'});
 const after=await page.locator('#dbDetails').innerText();
 if(!after.includes('IndexedDB')||!after.includes('Events'))throw Error('Database did not initialize after reload');
 const downloadPromise=page.waitForEvent('download');
 await page.click('#backupWorkspace');
 const dl=await downloadPromise;
 if(!dl.suggestedFilename().endsWith('.json'))throw Error('Workspace backup did not download');
 if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
 console.log(JSON.stringify({ok:true,dashboardMetrics:4,replay:'rate-limit recovery',signature:'valid + tamper rejected',database:'reload',backup:dl.suggestedFilename()}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
