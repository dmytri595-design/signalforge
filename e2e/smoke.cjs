const { chromium } = require('playwright');
const fs = require('node:fs');
fs.mkdirSync('artifacts/screenshots', { recursive: true });
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto(process.env.SMOKE_URL||'http://127.0.0.1:4173',{waitUntil:'networkidle'});
 await page.waitForSelector('#stats .stat');
 if(await page.locator('#stats .stat').count()!==4)throw Error('Dashboard metrics missing');
 if(await page.locator('#endpointCards .panel').count()===0)throw Error('Demo endpoints missing');
 const chartBars=page.locator('#healthChart .bar');
 if(await chartBars.count()!==14)throw Error('Delivery health chart should render 14 outcome bars across seven days');
 const visibleChartBars=await chartBars.evaluateAll(els=>els.some(el=>Number.parseFloat(getComputedStyle(el).height)>4&&Number.parseFloat(getComputedStyle(el).opacity)>0));
 if(!visibleChartBars)throw Error('Delivery health chart has no visible bars for the seeded demo outcomes');
 await page.screenshot({path:'artifacts/screenshots/01-dashboard.png',fullPage:true});
 await page.click('[data-view="replay"]');
 await page.selectOption('#replayProfile','rate-limit');
 await page.click('#runReplay');
 await page.waitForSelector('#replayTimeline .eventrow');
 const timeline=await page.locator('#replayTimeline').innerText();
 if(!timeline.includes('429')||!timeline.includes('Delivered successfully'))throw Error('Rate-limit retry scenario did not recover');
 await page.screenshot({path:'artifacts/screenshots/02-replay-lab.png',fullPage:true});
 await page.click('[data-view="signatures"]');
 await page.click('#generateSignature');
 await page.waitForSelector('#signatureOutput:not(.hidden)');
 await page.click('#verifyHmac');
 if(!(await page.locator('#verifyResult').innerText()).includes('VALID SIGNATURE'))throw Error('Valid HMAC did not verify');
 await page.click('#tamperBody');
 await page.click('#verifyHmac');
 if(!(await page.locator('#verifyResult').innerText()).includes('SIGNATURE MISMATCH'))throw Error('Tampered payload was not rejected');
 await page.fill('#signSecret','');
 await page.click('#verifyHmac');
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('.toast')).some(x=>x.textContent.includes('Secret and timestamp are required')));
 await page.fill('#signSecret','whsec_demo_local_only');
 await page.fill('#signTimestamp','not-a-timestamp');
 await page.click('#generateSignature');
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('.toast')).some(x=>x.textContent.includes('positive Unix timestamp')));
 await page.click('[data-view="idempotency"]');
 await page.click('#runIdempotency');
 await page.waitForSelector('#idemTimeline .eventrow');
 if(!(await page.locator('#idemResult').innerText()).includes('2'))throw Error('Idempotency simulator did not suppress duplicate deliveries');
 const idemState=await page.evaluate(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')));
 if(!idemState||!Array.isArray(idemState.idempotencyRuns)||!idemState.idempotencyRuns.length)throw Error('Idempotency history did not persist');
 await page.click('[data-view="contracts"]');
 await page.click('#compareContracts');
 await page.waitForSelector('#contractDiff table');
 if(!(await page.locator('#contractVerdict').innerText()).includes('BREAKING'))throw Error('Contract diff did not flag breaking changes');
 const contractState=await page.evaluate(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')));
 if(!contractState||!Array.isArray(contractState.contractRuns)||!contractState.contractRuns.length)throw Error('Contract comparison did not persist');
 const contractDlPromise=page.waitForEvent('download');
 await page.click('#exportContractReport');
 const contractDl=await contractDlPromise;
 if(!contractDl.suggestedFilename().endsWith('.md'))throw Error('Contract report export failed');

 await page.click('[data-view="events"]');
 await page.click('#newEvent');
 await page.locator('#modalFields input[name="type"]').fill('=2+2');
 await page.locator('#modalFields textarea[name="payload"]').fill('{"id":"formula-test","type":"formula-test","data":{"safe":true}}');
 await page.click('#modalSubmit');
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')).events.some(e=>e.type==='=2+2'));
 const eventCsvPromise=page.waitForEvent('download');
 await page.click('#exportEvents');
 const eventCsv=await eventCsvPromise;
 if(!eventCsv.suggestedFilename().endsWith('.csv'))throw Error('Event CSV export failed');
 const eventCsvPath=await eventCsv.path();
 const eventCsvText=fs.readFileSync(eventCsvPath,'utf8');
 if(!eventCsvText.includes("'=2+2"))throw Error('CSV formula-like event type was not escaped');

 const restoreData={version:2,settings:{name:'Restored test workspace',retention:90,seedOnReset:true},endpoints:[{id:'endpoint"><img src=x onerror=alert(1)>',name:'Restored profile',url:'https://receiver.example.test/restore',behavior:'healthy',secret:'demo_only',retry:{max:3,backoff:'fixed'}}],events:[{id:'event"><img src=x onerror=alert(1)>',type:'restore.test',endpointId:'endpoint"><img src=x onerror=alert(1)>',status:'pending',createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),attempts:0,payload:{id:'restore-payload'},attemptLog:[],tags:[]}],experiments:[],idempotencyRuns:[],contractRuns:[],activity:[]};
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#restoreFile').setInputFiles({name:'signalforge-restore-test.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(restoreData))});
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('.toast')).some(x=>x.textContent.includes('Workspace restored')));
 await page.click('[data-view="events"]');
 if(await page.locator('#eventsTable img').count()!==0)throw Error('Imported event identifier injected an HTML element');
 const restoredState=await page.evaluate(()=>JSON.parse(localStorage.getItem('signalforge:workspace:v1')));
 if(restoredState.events[0].id.includes('<')||restoredState.endpoints[0].id.includes('<'))throw Error('Imported record identifiers were not sanitized');
 await page.locator('[data-view="settings"]').first().click();
 await page.locator('#view-settings').waitFor({state:'visible'});
 const before=await page.locator('#dbDetails').innerText();
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-view="settings"]').first().click();
 await page.locator('#view-settings').waitFor({state:'visible'});
 const after=await page.locator('#dbDetails').innerText();
 if(!after.includes('IndexedDB')||!after.includes('Events'))throw Error('Database did not initialize after reload');
 const downloadPromise=page.waitForEvent('download');
 await page.click('#backupWorkspace');
 const dl=await downloadPromise;
 if(!dl.suggestedFilename().endsWith('.json'))throw Error('Workspace backup did not download');
 const fallbackContext=await browser.newContext();
 await fallbackContext.addInitScript(()=>{try{Object.defineProperty(window,'indexedDB',{configurable:true,value:undefined})}catch(e){}});
 const fallbackPage=await fallbackContext.newPage();
 const fallbackErrors=[];
 fallbackPage.on('pageerror',e=>fallbackErrors.push(String(e)));
 await fallbackPage.goto(process.env.SMOKE_URL||'http://127.0.0.1:4173',{waitUntil:'networkidle'});
 await fallbackPage.waitForSelector('#stats .stat');
 await fallbackPage.click('[data-view="settings"]');
 await fallbackPage.locator('#dbDetails').waitFor({state:'visible'});
 if(!(await fallbackPage.locator('#dbDetails').innerText()).includes('localStorage fallback'))throw Error('IndexedDB fallback mode did not initialize');
 await fallbackPage.fill('#workspaceName','Fallback persistence test');
 await fallbackPage.click('#saveSettings');
 await fallbackPage.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('Settings saved'));
 await fallbackPage.reload({waitUntil:'networkidle'});
 await fallbackPage.click('[data-view="settings"]');
 await fallbackPage.locator('#workspaceName').waitFor({state:'visible'});
 if(await fallbackPage.locator('#workspaceName').inputValue()!=='Fallback persistence test')throw Error('localStorage fallback did not persist settings across reload');
 if(fallbackErrors.length)throw Error('Fallback browser errors: '+fallbackErrors.join(' | '));
 await fallbackContext.close();

 if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
 console.log(JSON.stringify({ok:true,dashboardMetrics:4,replay:'rate-limit recovery',signature:'valid + tamper rejected + invalid input guarded',database:'IndexedDB + localStorage fallback reload',csv:'formula-like cells escaped',restore:'bounded and sanitized workspace import',backup:dl.suggestedFilename()}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
